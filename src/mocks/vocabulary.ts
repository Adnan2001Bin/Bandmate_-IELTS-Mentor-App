import type { VocabCategory, VocabCategoryId, VocabWord } from '@/types';

function word(
  categoryId: VocabCategoryId,
  slug: string,
  headword: string,
  meaning: string,
  example: string,
  synonyms: readonly string[],
  antonyms: readonly string[],
  ieltsContext: string,
): VocabWord {
  return {
    id: `${categoryId}-${slug}`,
    categoryId,
    headword,
    meaning,
    example,
    synonyms,
    antonyms,
    ieltsContext,
  };
}

