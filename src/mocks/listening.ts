import type { ListeningSet } from '@/types';

const MC = (
  id: string,
  number: number,
  prompt: string,
  options: readonly [string, string, string, string],
  correct: 'A' | 'B' | 'C' | 'D',
  explanation: string,
  miraCorrect: string,
  miraWrong: string,
  replayAtMs: number,
): ListeningSet['groups'][number]['questions'][number] => ({
  id,
  number,
  type: 'multipleChoice',
  prompt,
  options: [
    { id: 'A', label: options[0] },
    { id: 'B', label: options[1] },
    { id: 'C', label: options[2] },
    { id: 'D', label: options[3] },
  ],
  correct,
  explanation,
  miraCorrect,
  miraWrong,
  replayAtMs,
});

const blank = (
  type: ListeningSet['groups'][number]['questions'][number]['type'],
  id: string,
  number: number,
  prompt: string,
  correct: string | readonly string[],
  explanation: string,
  miraCorrect: string,
  miraWrong: string,
  replayAtMs: number,
  extra: Partial<ListeningSet['groups'][number]['questions'][number]> = {},
): ListeningSet['groups'][number]['questions'][number] => ({
  id,
  number,
  type,
  prompt,
  constraint: 'NO MORE THAN TWO WORDS AND/OR A NUMBER',
  correct,
  explanation,
  miraCorrect,
  miraWrong,
  replayAtMs,
  ...extra,
});

