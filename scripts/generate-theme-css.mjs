// Emits src/theme/global.css from src/theme/palette.ts so the NativeWind classes
// and the imperative theme object can never disagree. Run with `npm run theme`.
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { colorTokens, cssVarName, palettes, toRgbChannels } from '../src/theme/palette.ts';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const block = (scheme) =>
  colorTokens
    .map((token) => `  ${cssVarName(token)}: ${toRgbChannels(palettes[scheme][token])};`)
    .join('\n');

const css = `/* GENERATED by scripts/generate-theme-css.mjs — edit src/theme/palette.ts instead. */
@tailwind base;
@tailwind components;
@tailwind utilities;

@layer base {
  :root {
${block('light')}
  }

  .dark:root {
${block('dark')}
  }
}
`;

writeFileSync(resolve(root, 'src/theme/global.css'), css);
console.log(`Wrote src/theme/global.css (${colorTokens.length} tokens x 2 schemes)`);
